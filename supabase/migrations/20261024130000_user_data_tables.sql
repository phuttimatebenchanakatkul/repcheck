-- ---------------------------------------------------------------------------
-- Food log (repcheck_nutrition_log_v1)
-- ---------------------------------------------------------------------------

-- One row per logged food. `id` is client-generated (a UUID, or a
-- `${Date.now()}-${Math.random()}` fallback), so the pair (user_id, id) is the
-- key and an upsert is naturally idempotent, as /api/nutrition/log-entry was.
--
-- log_date is the calendar day the user filed it under; added_at is when. They
-- are independent on purpose: "Log macros" stamps Date.now() even when a past
-- day is selected, so added_at can fall on a different day than log_date, and
-- the hour shown in the UI is derived from added_at.
--
-- Two forms, never mixed: a SIMPLE entry has grams/unit/base_* and no
-- ingredients; a COMPOSITE entry has ingredients and none of those. Totals are
-- always computed from the per-100 g base_* values; none are stored per entry.
create table public.nutrition_entries (
    user_id       uuid not null references public.profiles (id) on delete cascade,
    id            text not null,
    log_date      date not null,
    food          text not null,
    added_at      timestamptz not null,
    source        text,                       -- 'scan' or NULL
    grams         double precision,
    unit          text,                       -- g | oz | ml
    base_calories double precision,           -- all four per 100 g
    base_carbs    double precision,
    base_fat      double precision,
    base_protein  double precision,
    -- [{name, grams, unit, baseCalories, baseCarbs, baseFat, baseProtein}]
    ingredients   jsonb check (ingredients is null or jsonb_typeof(ingredients) = 'array'),
    extra         jsonb not null default '{}',
    primary key (user_id, id)
);
create index idx_nutrition_entries_day on public.nutrition_entries (user_id, log_date);

