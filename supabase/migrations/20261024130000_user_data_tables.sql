);

-- repcheck_day_status_v1. Only OVERRIDES are stored: choosing "logged" or "none"
-- deletes the row to restore automatic detection.
create table public.day_status_overrides (
    user_id  uuid not null references public.profiles (id) on delete cascade,
    log_date date not null,
    status   text not null check (status in ('fasting', 'incomplete')),
    primary key (user_id, log_date)
);

-- repcheck_activity_log_v1: which actions counted toward a day's streak.
-- Client actions: challenge, coach_chat, checkin, analyze_chat, onboarding,
-- split_plan. (The server's back-fill of challenge/analysis/hyrox/checkin_photo
-- is computed at read time from the other tables, not stored here.) No CHECK:
-- new actions are added without a migration.
create table public.activity_days (
    user_id  uuid not null references public.profiles (id) on delete cascade,
    log_date date not null,
    action   text not null,
    primary key (user_id, log_date, action)
);

-- repcheck_analyze_log_v1: a client-side list of recent analyses
-- ({exercise, analyzedAt}), capped at 50 by the client, with NO id. The
-- unique key is what makes a re-push idempotent, standing in for the id the
-- entries never had.
create table public.analyze_log_entries (
    id          bigint generated by default as identity primary key,
    user_id     uuid not null references public.profiles (id) on delete cascade,
    exercise    text not null,
    analyzed_at timestamptz not null,
    unique (user_id, exercise, analyzed_at)
);

-- ---------------------------------------------------------------------------
-- HYROX race history (repcheck_hyrox_history_v1)
-- ---------------------------------------------------------------------------

-- Distinct from hyrox_results: that is the leaderboard row; this is the user's
-- full race record with splits and the AI analysis.
create table public.hyrox_races (
    user_id       uuid not null references public.profiles (id) on delete cascade,
    id            text not null,
    raced_at      timestamptz not null,   -- the old `date` is a full ISO UTC datetime
    category      text not null,          -- open | pro | custom
    format        text,                   -- singles | doubles; NULL for custom races
    gender        text,                   -- men | women; may be NULL
    scale         text not null default 'full',   -- full | half (old rows lack it: full)
    total_seconds double precision not null,
    flagged       boolean not null default false,
    is_new_pb     boolean not null default false,
    -- NULL until the AI race analysis runs. {overall, overallDetail[], tips[]}
    analysis      jsonb,
    extra         jsonb not null default '{}',
    primary key (user_id, id)
);
create index idx_hyrox_races_when on public.hyrox_races (user_id, raced_at);

-- `key` is run1..run8, skierg, sledPush, sledPull, burpeeBroadJump, row,
-- farmersCarry, lunges, wallBalls (custom races: run or a station key).
-- `title` is display text that depends on the user's units. at_seconds is
-- cumulative from the start of the race.
create table public.hyrox_race_splits (
    user_id    uuid not null,
    race_id    text not null,
    position   integer not null,
    key        text not null,
    title      text,
    at_seconds double precision not null,
    primary key (user_id, race_id, position),
    foreign key (user_id, race_id) references public.hyrox_races (user_id, id) on delete cascade
);

