-- RepCheck on Supabase: the data that lived as JSON blobs in SQLite's
-- user_data(user_id, key, value) and in the browser's localStorage, as tables.
--
-- Every shape below was traced from the code that WRITES it (see
-- MOBILE_APP_PLAN.md, "Synced data"), not from old rows: the keys
-- repcheck_*_v1 in app.py's SYNCED_DATA_KEYS and the per-analysis chat keys.
--
-- RULES FOR WHAT BECAME A TABLE AND WHAT STAYED JSON
--   * A row is independently queried or edited (a food entry, a set, a weigh-in,
--     a race, a chat turn)  ->  a table.
--   * One document always read and written whole (the split plan, a meal's
--     ingredient list, a race's AI analysis, a reply's source list)  ->  jsonb
--     inside its row. Splitting those would add joins and no capability.
--
-- RULES FOR CONSTRAINTS
--   Only rules the old server actually enforced are constraints. The old sync
--   route accepted any JSON for most keys; inventing stricter rules here would
--   reject real legacy rows at import time. The ones that were enforced:
--     * real calendar dates            -> `date` columns (9999-99-99 and
--                                         2026-02-31 were measured getting a 200)
--     * weight 0 < kg <= 400           -> weight_entries check
--     * a chat thread may only attach  -> composite foreign key to the user's
--       to the user's own analysis       own analyze_results row
--     * coaching profile: a required   -> trigger below
--       field is never dropped
--
-- Every table also has `extra jsonb`: fields the importer did not recognise
-- (old rows carry fields current code no longer writes, e.g. calories/name/hour
-- on a nutrition entry). Importing never silently discards a key.
--
-- NOT carried over from the old server, on purpose, and listed so it is a
-- decision rather than an accident: the 2 MiB-per-key and 200-entries-per-day
-- ceilings (app.py MAX_SYNC_VALUE_BYTES, /api/workout/log-day). The app can now
-- write these tables directly, so a per-user ceiling has to be re-decided here.

