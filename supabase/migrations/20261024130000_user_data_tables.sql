-- repcheck_coaching_profile_v1 plus the small coaching_* state keys.
-- Enum-like columns carry no CHECK: the old server validated them only on
-- /api/coaching/calculate and check-in, never on the sync write, so a legacy row
-- can hold anything. Values written by current code:
--   aspiration lose|maintain|gain, gender male|female, activity_level
--   none|cardio_only|lift_only|lift_and_cardio, protein_preference
--   low_moderate|moderate|high|highest, diet_preference
--   balanced|low_fat|low_carb|keto, distribution_mode stable|weekly.
create table public.coaching_profiles (
    user_id            uuid primary key references public.profiles (id) on delete cascade,
    -- The six fields a weekly check-in cannot run without. Nullable because
    -- legacy rows are known to be partial; see the trigger below.
    aspiration         text,
    gender             text,
    weight_kg          double precision,
    body_fat_range_id  text,          -- m1..m6 / f1..f6
    activity_level     text,
    protein_preference text,
    diet_preference    text,
    goal_weight_kg     double precision,
    height_cm          double precision,
    distribution_mode  text,
    loss_rate_pct      double precision,
    gain_rate_pct      double precision,
    created_on         date,          -- profile.createdAt (YYYY-MM-DD)
    last_adjustment_on date,          -- profile.lastAdjustmentDate
    -- repcheck_coaching_last_adjustment_v1 {reason, delta, at}
    last_adjustment_reason text,
    last_adjustment_delta  double precision,   -- kcal/day
    last_adjustment_at     timestamptz,
    -- repcheck_coaching_distribution_v1: {monday..sunday: {calories,protein,fat,carbs}}
    weekly_distribution jsonb,
    -- repcheck_coaching_goal_achieved_v1 / _handled_v1 {goalWeightKg, aspiration}
    goal_achieved_weight_kg  double precision,
    goal_achieved_aspiration text,
    goal_handled_weight_kg   double precision,
    goal_handled_aspiration  text,
    -- repcheck_coaching_inactivity_notified_v1 (local YYYY-MM-DD)
    inactivity_notified_on date,
    extra              jsonb not null default '{}'
);

-- database.py's _merge_coaching_profile_write(), moved to where the app can no
-- longer bypass it. A client holding a partial profile (an interrupted wizard
-- save, a half-finished hydration, a copy from an older build) used to push it
-- over the good copy and make every later check-in fail with "Please choose a
-- gender." naming a field the check-in never asks about. A real edit always goes
-- through the wizard, which sends every field, so keeping a stored value the
-- client blanked cannot block a legitimate change.
create function public.keep_required_coaching_fields()
returns trigger language plpgsql as $$
begin
    if new.aspiration         is null or new.aspiration = ''         then new.aspiration         := coalesce(nullif(old.aspiration, ''), new.aspiration); end if;
    if new.gender             is null or new.gender = ''             then new.gender             := coalesce(nullif(old.gender, ''), new.gender); end if;
    if new.weight_kg          is null                                then new.weight_kg          := old.weight_kg; end if;
    if new.body_fat_range_id  is null or new.body_fat_range_id = ''  then new.body_fat_range_id  := coalesce(nullif(old.body_fat_range_id, ''), new.body_fat_range_id); end if;
    if new.activity_level     is null or new.activity_level = ''     then new.activity_level     := coalesce(nullif(old.activity_level, ''), new.activity_level); end if;
    if new.protein_preference is null or new.protein_preference = '' then new.protein_preference := coalesce(nullif(old.protein_preference, ''), new.protein_preference); end if;
    return new;
end $$;
revoke execute on function public.keep_required_coaching_fields() from public, anon, authenticated;

create trigger coaching_profiles_keep_required
    before update on public.coaching_profiles
    for each row execute function public.keep_required_coaching_fields();

