-- Sets in the order the user logged them. Every numeric field is nullable
-- because the app writes "" for a field not filled in, and switching between
-- both-sides and each-side mode keeps both groups of fields.
create table public.workout_sets (
    user_id    uuid not null,
    entry_id   text not null,
    position   integer not null,
    reps       integer,
    weight_kg  double precision,      -- both-sides mode
    left_kg    double precision,      -- each-side mode
    right_kg   double precision,
    left_reps  integer,
    right_reps integer,
    extra      jsonb not null default '{}',
    primary key (user_id, entry_id, position),
    foreign key (user_id, entry_id) references public.workout_entries (user_id, id) on delete cascade
);

