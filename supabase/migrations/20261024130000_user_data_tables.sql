-- repcheck_analyze_chat_v1_<analyze_results.id>: one thread per analysis.
-- The composite foreign key is the old rule "the id must name one of THIS user's
-- own analyses" (app.py api_sync_put). Deleting an analysis deletes its thread,
-- which is what prune_analyze_results() did by hand. The thread's createdAtMs
