create index idx_analyze_chat_thread on public.analyze_chat_messages (user_id, analyze_result_id, seq);

-- ---------------------------------------------------------------------------
-- Grants and row-level security
-- ---------------------------------------------------------------------------
-- The app reads and writes ALL of these directly (offline-first), but only its
-- own rows. `with check` on insert/update stops a user reassigning a row to
-- someone else by changing user_id.

alter table public.import_quarantine enable row level security;   -- server-only
revoke all on public.import_quarantine from anon, authenticated;
grant all on public.import_quarantine to service_role;

do $$
declare
    t text;
begin
    foreach t in array array[
        'user_settings', 'nutrition_goals', 'nutrition_favorites', 'exercise_favorites',
        'coaching_profiles', 'split_plans', 'nutrition_entries', 'workout_entries',
        'workout_sets', 'weight_entries', 'day_status_overrides', 'activity_days',
        'analyze_log_entries', 'hyrox_races', 'hyrox_race_splits', 'coach_messages',
        'workout_chat_messages', 'analyze_chat_messages'
    ] loop
        execute format('alter table public.%I enable row level security', t);
        execute format('revoke all on public.%I from anon, authenticated', t);
        execute format('grant all on public.%I to service_role', t);
        execute format('grant select, insert, update, delete on public.%I to authenticated', t);
        execute format('create policy %I on public.%I for select to authenticated using (user_id = (select auth.uid()))',
                       t || '_select_own', t);
        execute format('create policy %I on public.%I for insert to authenticated with check (user_id = (select auth.uid()))',
                       t || '_insert_own', t);
        execute format('create policy %I on public.%I for update to authenticated '
                       'using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
                       t || '_update_own', t);
        execute format('create policy %I on public.%I for delete to authenticated using (user_id = (select auth.uid()))',
                       t || '_delete_own', t);
    end loop;
end $$;
