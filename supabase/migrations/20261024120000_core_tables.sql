-- RepCheck on Supabase: the tables that were already real tables in SQLite.
--
-- Source of truth for every column below is database.py's init_db() plus the
-- route code that writes it (app.py). Where a rule used to live in Flask and
-- the app can now reach the table directly, the rule is a constraint here --
-- or the table is left read-only to the app and writes stay behind Flask.
--
-- ACCESS MODEL (read before adding a table):
--   * The project was created with "automatically expose new tables" OFF, so
--     a new table is reachable by NOBODY until it is granted below.
--   * `anon` gets nothing, ever. `authenticated` (a signed-in app user) gets
--     only the grants listed per table, and RLS then limits those to the
--     caller's own rows (auth.uid()).
--   * `service_role` and the `postgres` owner (Flask's pooled connection)
--     bypass RLS. Flask is where cross-user reads, rate limits, moderation and
--     anything needing a secret live.
--
-- Postgres created these default privileges for tables made by `postgres` in
-- `public` (anon/authenticated/service_role = TRUNCATE, REFERENCES, TRIGGER,
-- MAINTAIN). TRUNCATE ignores RLS, so every table below starts with a blanket
-- REVOKE and is then granted exactly what it needs.

-- ---------------------------------------------------------------------------
-- Accounts
-- ---------------------------------------------------------------------------

-- One row per person. Email, provider and password live in auth.users
-- (Supabase Auth); this holds what RepCheck itself knows about them.
--
-- Deliberately absent from SQLite's users table:
--   theme, language   dead columns: database.update_preferences() is never
--                     called, every row holds the defaults, and the live
--                     values are the synced repcheck_theme / repcheck_language
--                     keys (see the settings table in the next migration).
--   rate_limited      vestigial per its own comment in init_db().
--   password_hash     moved to legacy_password_hashes (server-only).
--   auth_provider, provider_user_id
--                     Supabase Auth tracks these in auth.identities.
create table public.profiles (
    id                   uuid primary key references auth.users (id) on delete cascade,
    -- SQLite users.id this account was imported from. NULL for accounts
    -- created after the move. The import script's id map and its --reset
    -- both key off this column.
    legacy_user_id       integer unique,
    name                 text not null,
    avatar_url           text,
    friend_code          text unique,
    onboarding_completed boolean not null default false,
    -- When the user agreed to their content going to Google Gemini. NULL =
    -- never agreed or withdrew; the AI routes refuse until it is set.
    ai_consent_at        timestamptz,
    -- Start of the 30-day account-deletion grace period (Flask purges).
    deleted_at           timestamptz,
    created_at           timestamptz not null default now()
);

-- Werkzeug 3.1 scrypt hashes that Supabase Auth cannot import. Read once, at a
-- user's first sign-in after the move, to migrate the password (see the
-- "Passwords" section of MOBILE_APP_PLAN.md), then deleted. Server-only.
create table public.legacy_password_hashes (
    user_id       uuid primary key references public.profiles (id) on delete cascade,
    password_hash text not null
);

-- ---------------------------------------------------------------------------
-- Server-only bookkeeping (no app access of any kind)
-- ---------------------------------------------------------------------------

-- Per-user AI usage windows. Epoch seconds, as in SQLite.
create table public.rate_limits (
    user_id      uuid not null references public.profiles (id) on delete cascade,
    feature      text not null,
    window_start bigint not null,
    count        integer not null default 0,
    primary key (user_id, feature)
);

-- Throttle for actions before there is a user (failed logins, signups),
-- keyed on an opaque string, not a user id.
create table public.auth_throttle (
    key          text primary key,
    window_start bigint not null,
    count        integer not null default 0
);

-- Lifetime per-user usage counters for the admin activity view.
create table public.usage_events (
    user_id uuid not null references public.profiles (id) on delete cascade,
    event   text not null,
    count   integer not null default 0,
    last_at timestamptz not null default now(),
    primary key (user_id, event)
);

-- Reports against a person (App Review 1.2). Both sides cascade: a report whose
-- reported account is gone has nothing left to moderate (see _purge_user_rows).
create table public.content_reports (
    id          bigint generated by default as identity primary key,
    reporter_id uuid not null references public.profiles (id) on delete cascade,
    reported_id uuid not null references public.profiles (id) on delete cascade,
    reason      text not null,
    created_at  timestamptz not null default now(),
    handled_at  timestamptz
);
create index idx_content_reports_open on public.content_reports (handled_at, created_at);

-- Reports against an AI reply (App Review 4.7.1). The reply text is copied in
-- because the conversation itself lives only in the reporter's own storage.
create table public.ai_reports (
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references public.profiles (id) on delete cascade,
    feature    text not null,
    reason     text not null,
    reply_text text not null,
    created_at timestamptz not null default now(),
    handled_at timestamptz
);

-- Pre-launch waitlist from the marketing site. NOT accounts; email is stored
-- lowercased by the caller and UNIQUE so a second submit is idempotent.
create table public.waitlist (
    id         bigint generated by default as identity primary key,
    email      text not null unique,
    source     text,
    created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Social (cross-user: the app reads these through Flask, never directly)
-- ---------------------------------------------------------------------------

-- One row per direction (both inserted on add) so "my friends" is a single
-- indexed lookup, exactly as in SQLite.
create table public.friends (
    user_id    uuid not null references public.profiles (id) on delete cascade,
    friend_id  uuid not null references public.profiles (id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, friend_id)
);

create table public.challenges (
    id               bigint generated by default as identity primary key,
    creator_id       uuid not null references public.profiles (id) on delete cascade,
    exercise         text not null,
    duration_seconds integer not null default 25,
    created_at       timestamptz not null default now()
);

-- A user's best attempt per challenge. Deleting a challenge (its creator's
-- account going) removes everyone's submissions to it, as _purge_user_rows does.
create table public.challenge_submissions (
    challenge_id bigint not null references public.challenges (id) on delete cascade,
    user_id      uuid not null references public.profiles (id) on delete cascade,
    reps         integer not null,
    notes        text,
    created_at   timestamptz not null default now(),
    primary key (challenge_id, user_id)
);

-- One-way: the blocker's row. Flask reads both directions to hide each side
-- from the other; the app may only see and edit its OWN blocks.
-- `user_id <> blocked_id`: database.block_user() silently ignored a
-- self-block; here it is refused, since a client can now insert directly.
create table public.blocked_users (
    user_id    uuid not null references public.profiles (id) on delete cascade,
    blocked_id uuid not null references public.profiles (id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (user_id, blocked_id),
    check (user_id <> blocked_id)
);
create index idx_blocked_users_blocked on public.blocked_users (blocked_id);

-- ---------------------------------------------------------------------------
-- A user's own data that is validated by Flask on write (app reads only)
-- ---------------------------------------------------------------------------

-- Writes stay behind POST /api/custom-foods: it caps a user at 500 foods,
-- derives calories from the macros (never trusted from the client), digit-
-- strips the barcode and clamps lengths. None of that is reproduced here, so
-- the app gets SELECT only until it is.
create table public.custom_foods (
    id            bigint generated by default as identity primary key,
    user_id       uuid not null references public.profiles (id) on delete cascade,
    name          text not null,
    emoji         text not null,
    calories      double precision not null,
    protein       double precision not null,
    fat           double precision not null,
    carbs         double precision not null,
    barcode       text,
    serving_label text not null default '1 serving',
    serving_grams double precision not null default 100,
    created_at    timestamptz not null default now()
);
create unique index idx_custom_foods_user_barcode
    on public.custom_foods (user_id, barcode) where barcode is not null;

create table public.custom_food_servings (
    id             bigint generated by default as identity primary key,
    custom_food_id bigint not null references public.custom_foods (id) on delete cascade,
    label          text not null,
    grams          double precision not null
);
create index idx_custom_food_servings_food on public.custom_food_servings (custom_food_id);

-- Writes stay behind POST /api/custom-exercises (500 cap, name<=60, emoji<=8).
create table public.custom_exercises (
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references public.profiles (id) on delete cascade,
    name       text not null,
    emoji      text,
    mode       text not null default 'both' check (mode in ('both', 'each', 'either')),
    created_at timestamptz not null default now()
);

-- `filename` is the Storage object name; the object key is
-- '<user_id>/<filename>' in the private progress-photos bucket. `date` is the
-- check-in's own calendar day in the user's local time (no timezone shift) and
-- feeds the streak. Writes stay behind POST /api/checkin/photo, which only
-- accepts a date from the account's creation day up to tomorrow (a forged date
-- would invent streak history).
create table public.progress_photos (
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references public.profiles (id) on delete cascade,
    date       date not null,
    angle      text not null,
    filename   text not null,
    created_at timestamptz not null default now()
);

-- AI form analyses. Written by Flask when it grades a clip. `video_filename`
-- is the object name in the private analyze-videos bucket.
create table public.analyze_results (
    id             bigint generated by default as identity primary key,
    user_id        uuid not null references public.profiles (id) on delete cascade,
    exercise_label text not null,
    overall_score  integer,
    stretch_score  integer,
    squeeze_score  integer,
    favored        text,
    reps           integer,
    feedback_text  text not null,
    video_filename text,
    created_at     timestamptz not null default now()
);
create index idx_analyze_results_user on public.analyze_results (user_id, created_at desc);

-- Race results, also the HYROX leaderboard source (read across users by Flask).
create table public.hyrox_results (
    id            bigint generated by default as identity primary key,
    user_id       uuid not null references public.profiles (id) on delete cascade,
    gender        text not null,
    category      text not null,
    format        text not null,
    total_seconds double precision not null,
    created_at    timestamptz not null default now()
);
create index idx_hyrox_results_board on public.hyrox_results (gender, category, format, total_seconds);

