-- Tables with NO grant to `authenticated` and NO policy are unreachable from the
-- app: legacy_password_hashes, rate_limits, auth_throttle, usage_events,
-- content_reports, ai_reports, waitlist, friends, challenges,
-- challenge_submissions. Cross-user data (friends, challenges, leaderboards)
-- is served by Flask, which applies the block filter in both directions.

-- profiles: read your own; change only the onboarding flag. Name and avatar go
-- through Flask (the display-name filter, App Review 1.2, is Python and must not
-- be bypassable); friend_code, consent and deletion are Flask's too.
grant select on public.profiles to authenticated;
grant update (onboarding_completed) on public.profiles to authenticated;
create policy profiles_select_own on public.profiles
    for select to authenticated using (id = (select auth.uid()));
create policy profiles_update_own on public.profiles
    for update to authenticated
    using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- blocked_users: see, add and remove only your own blocks. Being blocked by
-- someone else is never shown to the blocked user.
grant select, insert, delete on public.blocked_users to authenticated;
create policy blocked_users_select_own on public.blocked_users
    for select to authenticated using (user_id = (select auth.uid()));
create policy blocked_users_insert_own on public.blocked_users
    for insert to authenticated with check (user_id = (select auth.uid()));
create policy blocked_users_delete_own on public.blocked_users
    for delete to authenticated using (user_id = (select auth.uid()));

-- Read-only own-data tables.
grant select on public.custom_foods, public.custom_food_servings, public.custom_exercises,
                public.progress_photos, public.analyze_results, public.hyrox_results
    to authenticated;
create policy custom_foods_select_own on public.custom_foods
    for select to authenticated using (user_id = (select auth.uid()));
create policy custom_food_servings_select_own on public.custom_food_servings
    for select to authenticated using (
        exists (select 1 from public.custom_foods f
                where f.id = custom_food_servings.custom_food_id
                  and f.user_id = (select auth.uid())));
create policy custom_exercises_select_own on public.custom_exercises
    for select to authenticated using (user_id = (select auth.uid()));
create policy progress_photos_select_own on public.progress_photos
    for select to authenticated using (user_id = (select auth.uid()));
create policy analyze_results_select_own on public.analyze_results
    for select to authenticated using (user_id = (select auth.uid()));
create policy hyrox_results_select_own on public.hyrox_results
    for select to authenticated using (user_id = (select auth.uid()));
