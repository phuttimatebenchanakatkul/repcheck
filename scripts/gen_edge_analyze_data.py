"""Generate supabase/functions/_shared/analyzeData.ts from analyze_form_gemini.py and trim_video.py, so the Edge Functions
grade a lift with exactly the website's exercise notes, prompt and numbers.

    python scripts/gen_edge_analyze_data.py            # rewrite the file
    python scripts/gen_edge_analyze_data.py --check    # exit 1 if it is stale (a test runs this)

The prompt is generated as two templates (with and without the research block) holding sentinels where the exercise's label,
notes, research and the clip length go; the TypeScript fills them in, and its own tests prove the result is byte-for-byte what
`build_prompt` writes for every exercise.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import analyze_form_gemini as gemini  # noqa: E402
import trim_video  # noqa: E402

TARGET = ROOT / "supabase" / "functions" / "_shared" / "analyzeData.ts"
LABEL, NOTES, RESEARCH, DURATION = ("\x00" + word + "\x00" for word in ("LABEL", "NOTES", "RESEARCH", "DURATION"))


def ts(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


def template(with_research):
    config = {"label": LABEL, "secondary_notes": NOTES}
    if with_research:
        config["research_notes"] = RESEARCH
    return gemini.build_prompt(config, DURATION)


def render():
    exercises = {key: {"label": cfg["label"], "secondary_notes": cfg["secondary_notes"], **({"research_notes": cfg["research_notes"]} if cfg.get("research_notes") else {})}
                 for key, cfg in gemini.EXERCISES.items()}
    constants = {
        "GEMINI_MODEL": gemini.GEMINI_MODEL, "SAMPLE_FPS": gemini.GEMINI_VIDEO_SAMPLE_FPS, "THINKING_LEVEL": gemini.GEMINI_THINKING_LEVEL,
        "MAX_SAFETY_BLOCK_RETRIES": gemini.MAX_SAFETY_BLOCK_RETRIES, "BUDGET_SECONDS": gemini.ANALYSIS_BUDGET_SECONDS,
        "MIN_ATTEMPT_SECONDS": gemini.MIN_ATTEMPT_SECONDS, "START_SECONDS": trim_video.START_SECONDS, "DURATION_SECONDS": trim_video.DURATION_SECONDS,
        "MIN_USABLE_SECONDS": trim_video.MIN_USABLE_SECONDS, "MIN_USABLE_BYTES": trim_video.MIN_USABLE_BYTES,
    }
    lines = [
        "// GENERATED by scripts/gen_edge_analyze_data.py from analyze_form_gemini.py and trim_video.py: do not edit by hand.",
        "// `python scripts/gen_edge_analyze_data.py` rewrites it; a test fails when it is stale.",
        "",
        "export interface ExerciseNotes {",
        "  label: string;",
        "  secondary_notes: string;",
        "  research_notes?: string;",
        "}",
        "",
        f"export const FORM_NUMBERS = {ts(constants)} as const;",
        "",
        f"export const EXERCISES: Readonly<Record<string, ExerciseNotes>> = {ts(exercises)};",
        "",
        f"export const GENERIC_SECONDARY_NOTES: string = {ts(gemini.GENERIC_SECONDARY_NOTES)};",
        "",
        "/** `build_prompt` with sentinels where the label, notes, research and clip length go. */",
        f"export const SENTINELS = {ts({'label': LABEL, 'notes': NOTES, 'research': RESEARCH, 'duration': DURATION})} as const;",
        f"export const PROMPT_WITH_RESEARCH: string = {ts(template(True))};",
        "",
        f"export const PROMPT_WITHOUT_RESEARCH: string = {ts(template(False))};",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
