"""Generate supabase/functions/_shared/titleData.ts: the characters whose str.title() is not what JavaScript's toUpperCase() gives
(the digraph "dž" has a title-case form, Georgian capitals are not used, "ß" is "Ss", and so on), so the Edge Functions capitalise
the way Python does.

    python scripts/gen_edge_title_data.py            # rewrite the file
    python scripts/gen_edge_title_data.py --check    # exit 1 if it is stale (a test runs this)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "supabase" / "functions" / "_shared" / "titleData.ts"


def render():
    table = {}
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        c = chr(cp)
        if c.title() != c.upper():
            table[c] = c.title()
    body = json.dumps(table, ensure_ascii=True, indent=2)
    return "\n".join([
        "// GENERATED by scripts/gen_edge_title_data.py from Python's str.title(): do not edit by hand.",
        "// `python scripts/gen_edge_title_data.py` rewrites it; a test fails when it is stale.",
        "",
        "/** The first letter of a word, where Python's title-case form is not the upper-case one. */",
        f"export const TITLE_FIRST: Readonly<Record<string, string>> = {body};",
        "",
    ])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
