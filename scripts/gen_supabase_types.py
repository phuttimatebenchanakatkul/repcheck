"""Generates mobile/src/supabase/database.types.ts from the live Supabase project: one entry per table the signed-in app can
actually read (the `authenticated` role has SELECT on it), in the shape @supabase/supabase-js expects.

Server-only tables (rate limits, reports, the waitlist, ...) are left out on purpose: the app must go through the Flask API
for those, and a type that exists invites a call that row-level security will refuse.

    python scripts/gen_supabase_types.py            # rewrite the file
    python scripts/gen_supabase_types.py --check    # exit 1 if it is out of date (tests/test_mobile_db_types.py does the same)

Needs SUPABASE_DB_URL (the pooler address) in the environment or .env, like the API. Read-only: it only queries the catalog.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

OUT = ROOT / "mobile" / "src" / "supabase" / "database.types.ts"

# Postgres type (pg_type.typname) -> TypeScript. Anything not listed fails the run: a new type is a decision, not a guess.
SCALARS = {
    "uuid": "string", "text": "string", "varchar": "string", "bpchar": "string", "citext": "string",
    "date": "string", "timestamptz": "string", "timestamp": "string", "time": "string", "timetz": "string",
    "int2": "number", "int4": "number", "int8": "number", "float4": "number", "float8": "number", "numeric": "number",
    "bool": "boolean", "json": "Json", "jsonb": "Json",
}

TABLES_SQL = """
select c.relname as name
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind in ('r', 'p')
  and has_table_privilege('authenticated', c.oid, 'select')
order by c.relname
"""

COLUMNS_SQL = """
select a.attname as name, t.typname as type, t.typcategory as category, a.attnotnull as not_null,
       (a.atthasdef or a.attidentity <> '' or a.attgenerated <> '') as has_default,
       et.typname as element_type
from pg_attribute a
join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
join pg_type t on t.oid = a.atttypid
left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
where n.nspname = 'public' and c.relname = %s and a.attnum > 0 and not a.attisdropped
order by a.attnum
"""

HEADER = """// GENERATED by scripts/gen_supabase_types.py from the live Supabase project. Do not edit by hand:
// run `python scripts/gen_supabase_types.py` after a migration (tests/test_mobile_db_types.py fails when this is stale).
// Only tables the signed-in app can read appear here; everything else goes through the Flask API.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];
"""


def ts_type(column):
    if column["category"] == "A":
        element = column["element_type"].lstrip("_")
        if element not in SCALARS:
            raise SystemExit(f"{column['name']}: no TypeScript type for array of {element!r}; add it to SCALARS")
        return f"{SCALARS[element]}[]"
    if column["type"] not in SCALARS:
        raise SystemExit(f"{column['name']}: no TypeScript type for Postgres type {column['type']!r}; add it to SCALARS")
    return SCALARS[column["type"]]


def render_table(name, columns):
    row, insert, update = [], [], []
    for c in columns:
        t = ts_type(c)
        key = c["name"]
        row.append(f"          {key}: {t}{'' if c['not_null'] else ' | null'}")
        required = c["not_null"] and not c["has_default"]
        insert.append(f"          {key}{'' if required else '?'}: {t}{' | null' if not c['not_null'] else ''}")
        update.append(f"          {key}?: {t}{' | null' if not c['not_null'] else ''}")
    body = lambda lines: "\n".join(f"{line}" for line in lines)
    return (f"      {name}: {{\n        Row: {{\n{body(row)}\n        }}\n        Insert: {{\n{body(insert)}\n        }}\n"
            f"        Update: {{\n{body(update)}\n        }}\n        Relationships: []\n      }}")


def generate(conn):
    tables = [r["name"] for r in conn.execute(TABLES_SQL).fetchall()]
    blocks = [render_table(name, conn.execute(COLUMNS_SQL, (name,)).fetchall()) for name in tables]
    return (HEADER + "\nexport type Database = {\n  public: {\n    Tables: {\n" + "\n".join(blocks) +
            "\n    }\n    Views: { [_ in never]: never }\n    Functions: { [_ in never]: never }\n    Enums: { [_ in never]: never }\n  }\n}\n")


def main(argv):
    from api.db import Database
    from api.settings import from_env

    db = Database(from_env().db_url)
    try:
        with db.connection() as conn:
            text = generate(conn)
    finally:
        db.close()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("database.types.ts is out of date: run python scripts/gen_supabase_types.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
