"""Generate supabase/functions/_shared/challengeData.ts from rep_form_analyzer.py and video_trimmer.py, so the Edge Functions count a
challenge clip with exactly the website's instructions and numbers.

    python scripts/gen_edge_challenge_data.py            # rewrite the file
    python scripts/gen_edge_challenge_data.py --check    # exit 1 if it is stale (a test runs this)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import rep_form_analyzer as rfa  # noqa: E402
import video_trimmer  # noqa: E402

TARGET = ROOT / "supabase" / "functions" / "_shared" / "challengeData.ts"


def ts(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


def render():
    numbers = {"GEMINI_MODEL": rfa.GEMINI_MODEL, "SAMPLE_FPS": rfa.GEMINI_VIDEO_SAMPLE_FPS, "MAX_SAFETY_BLOCK_RETRIES": rfa.MAX_SAFETY_BLOCK_RETRIES,
               "CHALLENGE_SECONDS": video_trimmer.CHALLENGE_SECONDS}
    labels = {key: cfg["label"] for key, cfg in rfa.CHALLENGE_EXERCISES.items()}
    prompts = {key: rfa.build_prompt(key) for key in rfa.CHALLENGE_EXERCISES}
    return "\n".join([
        "// GENERATED by scripts/gen_edge_challenge_data.py from rep_form_analyzer.py and video_trimmer.py: do not edit by hand.",
        "// `python scripts/gen_edge_challenge_data.py` rewrites it; a test fails when it is stale.",
        "",
        f"export const CHALLENGE_NUMBERS = {ts(numbers)} as const;",
        "",
        f"export const CHALLENGE_LABELS: Readonly<Record<string, string>> = {ts(labels)};",
        "",
        "/** The instructions for each exercise, exactly what `build_prompt` writes. */",
        f"export const CHALLENGE_PROMPTS: Readonly<Record<string, string>> = {ts(prompts)};",
        "",
    ])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
