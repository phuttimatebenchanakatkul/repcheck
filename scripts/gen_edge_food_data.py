"""Generate supabase/functions/_shared/foodData.ts from the Python food modules, so the Edge Functions carry exactly the
website's food-photo prompt and the lookup constants (plausible-nutrition bounds, product-database addresses, time limits).

    python scripts/gen_edge_food_data.py            # rewrite the file
    python scripts/gen_edge_food_data.py --check    # exit 1 if it is stale (a test runs this)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import analyze_food_gemini  # noqa: E402
import barcode_scanner  # noqa: E402
import fatsecret_lookup  # noqa: E402

TARGET = ROOT / "supabase" / "functions" / "_shared" / "foodData.ts"


def ts(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


def render():
    lines = [
        "// GENERATED by scripts/gen_edge_food_data.py from analyze_food_gemini.py, barcode_scanner.py and fatsecret_lookup.py: do not edit by hand.",
        "// `python scripts/gen_edge_food_data.py` rewrites it; a test fails when it is stale.",
        "",
        f"export const FOOD_SYSTEM_PROMPT: string = {ts(analyze_food_gemini.SYSTEM_PROMPT)};",
        "",
    ]
    for name, value in (
        ("MAX_INGREDIENTS", analyze_food_gemini.MAX_INGREDIENTS),
        ("KJ_PER_KCAL", barcode_scanner.KJ_PER_KCAL),
        ("MAX_PLAUSIBLE_MACRO_G", barcode_scanner.MAX_PLAUSIBLE_MACRO_G),
        ("MAX_PLAUSIBLE_KCAL", barcode_scanner.MAX_PLAUSIBLE_KCAL),
        ("LOOKUP_TIMEOUT_SECONDS", barcode_scanner.REQUEST_TIMEOUT_SECONDS),
        ("OPEN_FOOD_FACTS_URL", barcode_scanner.OPEN_FOOD_FACTS_URL),
        ("OPEN_FOOD_FACTS_SEARCH_URL", barcode_scanner.OPEN_FOOD_FACTS_SEARCH_URL),
        ("FATSECRET_TIMEOUT_SECONDS", fatsecret_lookup.REQUEST_TIMEOUT_SECONDS),
        ("FATSECRET_TOKEN_URL", fatsecret_lookup.TOKEN_URL),
        ("FATSECRET_BARCODE_URL", fatsecret_lookup.BARCODE_URL),
        ("FATSECRET_FOOD_URL", fatsecret_lookup.FOOD_URL),
    ):
        lines.append(f"export const {name} = {json.dumps(value)};")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
