"""Generate supabase/functions/_shared/nameFilterData.ts from name_filter.py, so the Edge Function's display-name filter
holds exactly the word list the Python one does, and strips exactly the characters Python's `unicodedata.combining`
does (JavaScript has no combining-class lookup of its own).

    python scripts/gen_edge_name_filter.py            # rewrite the file
    python scripts/gen_edge_name_filter.py --check    # exit 1 if it is stale (a test runs this)
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import name_filter  # noqa: E402

TARGET = ROOT / "supabase" / "functions" / "_shared" / "nameFilterData.ts"


def combining_ranges():
    ranges, start, prev = [], None, None
    for cp in range(0x110000):
        if unicodedata.combining(chr(cp)):
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            ranges.append((start, prev))
            start = None
    if start is not None:
        ranges.append((start, prev))
    return ranges


def render():
    words = sorted(name_filter._BAD_WORDS)
    lines = [
        "// GENERATED by scripts/gen_edge_name_filter.py from name_filter.py: do not edit by hand.",
        "// `python scripts/gen_edge_name_filter.py` rewrites it; a test fails when it is stale.",
        "",
        "export const BAD_WORDS: readonly string[] = [",
    ]
    lines += [f'  "{w}",' for w in words]
    lines += [
        "];",
        "",
        f"// Every code point whose canonical combining class is not 0, as [first, last] pairs (Python's unicodedata {unicodedata.unidata_version}).",
        "export const COMBINING: readonly (readonly [number, number])[] = [",
    ]
    lines += [f"  [0x{a:X}, 0x{b:X}]," for a, b in combining_ranges()]
    lines += ["];", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current == text:
            sys.exit(0)
        # A different Python may know a newer Unicode: then only the word list is compared (the table is a snapshot).
        if f"unicodedata {unicodedata.unidata_version})" not in current:
            head = lambda t: t.split("// Every code point")[0]       # noqa: E731
            sys.exit(0 if head(current) == head(text) else 1)
        sys.exit(1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
