"""Generate supabase/functions/_shared/workoutData.ts from workout_library.py, so the Edge Functions' split generator
draws on exactly the website's exercise library (the categories in their order, and where each exercise can be done).

    python scripts/gen_edge_workout_data.py            # rewrite the file
    python scripts/gen_edge_workout_data.py --check    # exit 1 if it is stale (a test runs this)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import workout_library as wl  # noqa: E402

TARGET = ROOT / "supabase" / "functions" / "_shared" / "workoutData.ts"


def ts(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


def render():
    return "\n".join([
        "// GENERATED by scripts/gen_edge_workout_data.py from workout_library.py: do not edit by hand.",
        "// `python scripts/gen_edge_workout_data.py` rewrites it; a test fails when it is stale.",
        "",
        "/** Every category's exercises, categories in the website's order. */",
        f"export const EXERCISE_CATEGORIES: Readonly<Record<string, readonly string[]>> = {ts(wl.EXERCISE_CATEGORIES)};",
        "",
        "/** Where each exercise can be done: \"home\", \"gym\" or \"both\". */",
        f"export const EXERCISE_LOCATIONS: Readonly<Record<string, string>> = {ts(wl.EXERCISE_LOCATIONS)};",
        "",
    ])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
