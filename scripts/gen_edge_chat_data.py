"""Generate supabase/functions/_shared/chatData.ts from the Python modules, so the Edge Functions carry exactly the texts the
website's AI chats do: the Coach's system prompt, and the catalog of health sources the chats cite (which App Review checks).

    python scripts/gen_edge_chat_data.py            # rewrite the file
    python scripts/gen_edge_chat_data.py --check    # exit 1 if it is stale (a test runs this)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import coach_chat  # noqa: E402
import health_sources  # noqa: E402

TARGET = ROOT / "supabase" / "functions" / "_shared" / "chatData.ts"


def ts(value):
    """A JSON literal TypeScript reads as the same value (ensure_ascii off: the text stays readable)."""
    return json.dumps(value, ensure_ascii=False, indent=2)


def render():
    return "\n".join([
        "// GENERATED by scripts/gen_edge_chat_data.py from coach_chat.py and health_sources.py: do not edit by hand.",
        "// `python scripts/gen_edge_chat_data.py` rewrites it; a test fails when it is stale.",
        "",
        "export interface Source {",
        "  id: string;",
        "  topic: string;",
        "  title: string;",
        "  publisher: string;",
        "  url: string;",
        "}",
        "",
        f"export const COACH_SYSTEM_PROMPT: string = {ts(coach_chat.SYSTEM_PROMPT)};",
        "",
        f"export const TOPICS: readonly (readonly [string, string])[] = {ts([list(t) for t in health_sources.TOPICS])};",
        "",
        f"export const SOURCES: readonly Source[] = {ts(health_sources.SOURCES)};",
        "",
    ])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
