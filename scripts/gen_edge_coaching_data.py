"""Generate supabase/functions/_shared/coachingData.ts from coaching_engine.py, so the Edge Functions use exactly the
website's body-fat ranges and tuning constants (the computed ones included, written the way Python prints them).

    python scripts/gen_edge_coaching_data.py            # rewrite the file
    python scripts/gen_edge_coaching_data.py --check    # exit 1 if it is stale (a test runs this)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import coaching_engine as ce  # noqa: E402

TARGET = ROOT / "supabase" / "functions" / "_shared" / "coachingData.ts"

NUMBERS = (
    "RATE_REFERENCE_WEIGHT_KG", "LOSS_STANDARD_MIN_KG_PER_WEEK", "LOSS_STANDARD_MAX_KG_PER_WEEK", "LOSS_RATE_MIN_PCT", "LOSS_RATE_MAX_PCT",
    "LOSS_RATE_DEFAULT_PCT", "LOSS_RATE_DEFICIT_FRACTION_MIN", "LOSS_RATE_DEFICIT_FRACTION_MAX", "GAIN_RATE_MIN_PCT", "GAIN_STANDARD_MAX_KG_PER_WEEK",
    "GAIN_RATE_MAX_PCT", "GAIN_RATE_DEFAULT_PCT", "GAIN_RATE_SURPLUS_FRACTION_MIN", "GAIN_RATE_SURPLUS_FRACTION_MAX", "MIN_CALORIES_MALE",
    "MIN_CALORIES_FEMALE", "FAT_PERCENT_OF_CALORIES", "WEEKLY_ADJUSTMENT_LIMIT", "KETO_CARBS_G",
)
TABLES = ("ACTIVITY_MULTIPLIERS", "ACTIVITY_PROTEIN_MULTIPLIER", "ASPIRATION_ADJUSTMENT", "PROTEIN_G_PER_KG_LEAN", "LOSE_WEIGHT_PROTEIN_BUMP_G", "DIET_FAT_PERCENT_OF_CALORIES")


def ts(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


def render():
    lines = [
        "// GENERATED by scripts/gen_edge_coaching_data.py from coaching_engine.py: do not edit by hand.",
        "// `python scripts/gen_edge_coaching_data.py` rewrites it; a test fails when it is stale.",
        "",
        "export interface BodyFatRange {",
        "  id: string;",
        "  label: string;",
        "  min: number;",
        "  max: number;",
        "  desc: string;",
        "}",
        "",
        f"export const MALE_BODY_FAT_RANGES: readonly BodyFatRange[] = {ts(ce.MALE_BODY_FAT_RANGES)};",
        "",
        f"export const FEMALE_BODY_FAT_RANGES: readonly BodyFatRange[] = {ts(ce.FEMALE_BODY_FAT_RANGES)};",
        "",
    ]
    for name in NUMBERS:
        lines.append(f"export const {name} = {json.dumps(getattr(ce, name))};")
    lines.append("")
    for name in TABLES:
        lines.append(f"export const {name}: Readonly<Record<string, number>> = {ts(getattr(ce, name))};")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
